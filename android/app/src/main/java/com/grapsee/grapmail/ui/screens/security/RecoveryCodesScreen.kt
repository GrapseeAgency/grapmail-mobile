/**
 * Account recovery codes — the ten one-time "XXXX-XXXX-XXXX" strings the
 * /recovery/codes endpoints mint, which stand in for a second factor on the
 * forgot-password screen when neither the phone nor a trusted device can help.
 *
 * These are NOT the two-step backup codes (screen 07/08): those prove a
 * sign-in's second factor. These codes reset a password. The screen says so,
 * because two lists of ten one-time codes in one app is exactly where a person
 * grabs the wrong list at the worst moment.
 *
 * The generated set lives in this screen's state only — never a navigation
 * argument, never [SecurityFlow] — and the server keeps hashes, so the copy a
 * person takes here is the only readable copy that will ever exist. Leaving
 * without confirming takes the same explicit dialog the backup-codes screen
 * uses, for the same reason.
 */
@Composable
fun RecoveryCodesScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val palette = LocalPalette.current
    val clipboard = LocalClipboardManager.current
    // Null while the status read is outstanding; a server that did not answer
    // is not an account with no codes.
    var usable by remember { mutableStateOf<Boolean?>(null) }
    var loading by remember { mutableStateOf(true) }
    var failed by remember { mutableStateOf(false) }
    var generating by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    // The fresh set, held for exactly as long as this screen chain exists.
    var generated by remember { mutableStateOf<List<String>?>(null) }
    var copied by remember { mutableStateOf(false) }
    var copiedOne by remember { mutableStateOf<String?>(null) }
    var confirmed by remember { mutableStateOf(false) }
    var leaving by remember { mutableStateOf(false) }

    fun reloadStatus() {
        scope.launch {
            loading = true
            failed = false
            try {
                val token = SessionStore.token(context) ?: throw IllegalStateException("Sign in again.")
                usable = Api.recoveryCodesStatus(token).usable
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                failed = true
            } finally {
                loading = false
            }
        }
    }

    fun generate() {
        scope.launch {
            generating = true
            error = null
            try {
                val token = SessionStore.token(context) ?: throw IllegalStateException("Sign in again.")
                val resp = Api.generateRecoveryCodes(token)
                if (resp.codes.isEmpty()) throw IllegalStateException("The server returned no codes. Try again.")
                // A fresh set retires every earlier one — the gate resets with it.
                generated = resp.codes
                confirmed = false
                copied = false
                copiedOne = null
                usable = true
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                error = e.message
            } finally {
                generating = false
            }
        }
    }

    LaunchedEffect(Unit) { reloadStatus() }

    val codes = generated
    // Leaving with an unsaved set loses it; the system back gesture used to
    // bypass that guard on the backup-codes screen, so it is handled here too.
    BackHandler(enabled = codes != null && !confirmed) {
        if (confirmed) onBack() else leaving = true
    }
    val download = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("text/plain")) { uri ->
        if (uri != null) {
            runCatching {
                context.contentResolver.openOutputStream(uri)?.use { out ->
                    out.write((codes ?: emptyList()).joinToString("\r\n").toByteArray())
                }
            }
        }
    }

    AccountScreen(
        onBack = { if (codes != null && !confirmed) leaving = true else onBack() },
        illustration = "ill_sec_backup_generate",
        illustrationWidth = 150,
        title = "Recovery Codes",
        body = "One-time codes that unlock password recovery when your phone and your trusted device are both unavailable.",
        footer = {
            Column {
                if (codes == null) {
                    GradientButton(
                        "Generate Codes",
                        onClick = { generate() },
                        busy = generating,
                    )
                    Spacer(Modifier.height(6.dp))
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.Center) {
                        AccountLink("Back to Account Security", onBack)
                    }
                } else {
                    GradientButton(
                        "Download Codes",
                        trailing = { Icon(Icons.Rounded.Download, contentDescription = null, modifier = Modifier.padding(start = 6.dp)) },
                        onClick = {
                            try {
                                download.launch("grapmail-recovery-codes.txt")
                            } catch (e: ActivityNotFoundException) {
                                // No file handler: the clipboard still gets the
                                // codes out — same fallback the backup screen runs.
                                clipboard.setText(AnnotatedString(codes.joinToString("\n")))
                                copied = true
                            }
                        },
                    )
                    Spacer(Modifier.height(8.dp))
                    GradientButton("Done", { onBack() }, enabled = confirmed)
                    Spacer(Modifier.height(4.dp))
                    FooterNote(
                        text = "Generating a new set retires every code on this list.",
                        divider = true,
                    )
                }
            }
        },
    ) {
        if (codes == null) {
            // Status row: the server's own answer, drawn as unknown while the
            // read is outstanding — "no" invites a generate, "unknown" must not.
            InfoCard {
                Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                    Icon(Icons.Rounded.Key, contentDescription = null, tint = palette.primarySolid, modifier = Modifier.size(18.dp))
                    Column(Modifier.weight(1f)) {
                        Text("Recovery codes available", fontSize = 13.sp, fontWeight = FontWeight.SemiBold, color = palette.textPrimary)
                        Text(
                            when {
                                loading -> "Checking…"
                                failed -> "Could not be read. Try again."
                                usable == true -> "Yes — a usable set exists on the account."
                                usable == false -> "No — generate a set to keep a recovery path open."
                                else -> "The account's status could not be read."
                            },
                            fontSize = 12.sp,
                            lineHeight = 17.sp,
                            color = if (usable == false && !loading && !failed) palette.warnInk else palette.textSecondary,
                        )
                    }
                    if (failed) {
                        AccountLink("Retry", { reloadStatus() })
                    } else if (!loading && usable != null) {
                        StatusChip(if (usable == true) "Yes" else "No", if (usable == true) ChipTone.Success else ChipTone.Warning)
                    }
                }
            }
            Spacer(Modifier.height(12.dp))
            InfoCard {
                Text("What's Included", fontSize = 14.sp, fontWeight = FontWeight.SemiBold, color = palette.textPrimary)
                Spacer(Modifier.height(10.dp))
                RecoveryPoint(Icons.Rounded.Key, "10 One-Time Codes", "Each code resets the password once.")
                RecoveryPoint(Icons.Rounded.Download, "Use at Forgot Password", "Enter a code instead of the texted one.")
                RecoveryPoint(Icons.Rounded.Refresh, "Regenerate Anytime", "A new set retires the old one immediately.")
            }
            if (error != null) {
                Spacer(Modifier.height(8.dp))
                Text(error!!, fontSize = 12.sp, color = palette.error)
            }
            Spacer(Modifier.height(12.dp))
            InfoNoteCard(
                title = "Not the same as backup codes",
                body = "Two-step backup codes prove a sign-in. Recovery codes reset a password. Keep both, and do not store them in the same place.",
            )
        } else {
            InfoCard {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text("Your Recovery Codes", fontSize = 14.sp, fontWeight = FontWeight.SemiBold, color = palette.textPrimary)
                    Spacer(Modifier.weight(1f))
                    Row(
                        Modifier
                            .clip(RoundedCornerShape(10.dp))
                            .clickable {
                                clipboard.setText(AnnotatedString(codes.joinToString("\n")))
                                copied = true
                            }
                            .padding(horizontal = 8.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(5.dp),
                    ) {
                        Icon(
                            if (copied) Icons.Rounded.CheckCircle else Icons.Rounded.ContentCopy,
                            contentDescription = null,
                            tint = palette.primarySolid,
                            modifier = Modifier.size(14.dp),
                        )
                        Text(if (copied) "Copied" else "Copy all", fontSize = 12.sp, fontWeight = FontWeight.SemiBold, color = palette.primarySolid)
                    }
                }
                Spacer(Modifier.height(12.dp))
                Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                    codes.chunked(2).forEach { pair ->
                        Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                            pair.forEach { code ->
                                Box(
                                    Modifier
                                        .weight(1f)
                                        .clip(RoundedCornerShape(10.dp))
                                        .background(palette.softFill)
                                        .clickable {
                                            clipboard.setText(AnnotatedString(code))
                                            copiedOne = code
                                        }
                                        .padding(vertical = 9.dp, horizontal = 8.dp),
                                ) {
                                    Row(
                                        Modifier.fillMaxWidth(),
                                        verticalAlignment = Alignment.CenterVertically,
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                    ) {
                                        Text(
                                            code,
                                            fontSize = 13.sp,
                                            fontWeight = FontWeight.SemiBold,
                                            fontFamily = FontFamily.Monospace,
                                            color = palette.textPrimary,
                                        )
                                        Icon(
                                            if (copiedOne == code) Icons.Rounded.CheckCircle else Icons.Rounded.ContentCopy,
                                            contentDescription = "Copy $code",
                                            tint = palette.textTertiary,
                                            modifier = Modifier.size(14.dp),
                                        )
                                    }
                                }
                            }
                            if (pair.size == 1) Spacer(Modifier.weight(1f))
                        }
                    }
                }
            }
            Spacer(Modifier.height(12.dp))
            BulletCard(
                "Keep them safe",
                listOf(
                    "One time use — each code resets the password exactly once.",
                    "Codes are stored as hashes — this list is the only readable copy.",
                    "Generating a new set retires every code shown here.",
                ),
            )
            Spacer(Modifier.height(12.dp))
            TermsCheckbox(confirmed, { confirmed = it }) {
                Text(
                    "I have saved these codes somewhere safe.",
                    fontSize = 13.sp,
                    color = palette.textPrimary,
                )
            }
            if (error != null) {
                Spacer(Modifier.height(8.dp))
                Text(error!!, fontSize = 12.sp, color = palette.error)
            }
        }
    }

    if (leaving) {
        AlertDialog(
            onDismissRequest = { leaving = false },
            title = { Text("These codes will not be shown again") },
            text = { Text("Leave now and the list is gone. The codes themselves keep working — but only if you already saved them.") },
            confirmButton = {
                TextButton(onClick = { leaving = false; onBack() }) { Text("Leave anyway") }
            },
            dismissButton = {
                TextButton(onClick = { leaving = false }) { Text("Stay") }
            },
        )
    }
}

@Composable
private fun RecoveryPoint(icon: androidx.compose.ui.graphics.vector.ImageVector, title: String, body: String) {
    val palette = LocalPalette.current
    Row(Modifier.padding(vertical = 7.dp), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
        Icon(icon, contentDescription = null, tint = palette.primarySolid, modifier = Modifier.size(18.dp))
        Column {
            Text(title, fontSize = 13.sp, fontWeight = FontWeight.SemiBold, color = palette.textPrimary)
            Text(body, fontSize = 12.sp, color = palette.textSecondary)
        }
    }
}
